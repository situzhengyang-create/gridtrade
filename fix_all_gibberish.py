# 读取文件
with open('src/App.tsx', 'rb') as f:
    content = f.read()

# 修复所有可能的乱码模式
# 使用十六进制转义序列
gibberish_patterns = [
    (b'\xef\xbf\xbd?\\)', b'\xe6\x8b\xa4\\)'),  # 回撤的乱码
    (b'\xef\xbf\xbd?\'', b'\xe6\x8b\xa4\''),
    (b'\xe5\x9b\x9e\xef\xbf\xbd', b'\xe5\x9b\x9e\xe6\x8b\xa4'),  # 回撤
]

for old, new in gibberish_patterns:
    content = content.replace(old, new)

# 修复特定的乱码字符串: '未获取到有效的价格数据'
old_str = b"\xe6\x9c\xaa\xe8\x8e\xb7\xe5\x8f\x96\xe5\x88\xb0\xe6\x9c\x89\xe6\x95\x88\xe7\x9a\x84\xe4\xbb\xb7\xe6\xa0\xbc\xe6\x95\xb0\xe6\x89\x8b\xef\xbf\xbd'"
new_str = b"\xe6\x9c\xaa\xe8\x8e\xb7\xe5\x8f\x96\xe5\x88\xb0\xe6\x9c\x89\xe6\x95\x88\xe7\x9a\x84\xe4\xbb\xb7\xe6\xa0\xbc\xe6\x95\xb0\xe6\x89\x8b'"
content = content.replace(old_str, new_str)

old_str2 = b"\xe6\x9c\xaa\xe8\x8e\xb7\xe5\x8f\x96\xe5\x88\xb0\xe6\x9c\x89\xe6\x95\x88\xe7\x9a\x84\xe4\xbb\xb7\xe6\xa0\xbc\xe6\x95\xb0\xe6\x89\x8b\xef\xbf\xbd)"
new_str2 = b"\xe6\x9c\xaa\xe8\x8e\xb7\xe5\x8f\x96\xe5\x88\xb0\xe6\x9c\x89\xe6\x95\x88\xe7\x9a\x84\xe4\xbb\xb7\xe6\xa0\xbc\xe6\x95\xb0\xe6\x89\x8b)"
content = content.replace(old_str2, new_str2)

# 写入文件
with open('src/App.tsx', 'wb') as f:
    f.write(content)

print('All gibberish fixed successfully')
